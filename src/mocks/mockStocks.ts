// Generate K-Line Data generator for historical trends
export function generateMockKLines(
  basePrice: number = 1482.35,
  points: number = 60
): KLinePoint[] {
  const result: KLinePoint[] = [];
  let currentPrice = basePrice * 0.85;
  const now = new Date();

  for (let i = points; i >= 0; i--) {
    const date = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = date.toISOString().split('T')[0];

    const change = (Math.random() - 0.48) * (basePrice * 0.025);
    const open = Math.round(currentPrice * 100) / 100;
    const close = Math.round(Math.max(1, currentPrice + change) * 100) / 100;
    const high = Math.round(Math.max(open, close) * (1 + Math.random() * 0.015) * 100) / 100;
    const low = Math.round(Math.min(open, close) * (1 - Math.random() * 0.015) * 100) / 100;
    const volume = Math.round(10000 + Math.random() * 80000);

    currentPrice = close;

    result.push({
      time: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  // Calculate Moving Averages MA5, MA20, MA60
  for (let i = 0; i < result.length; i++) {
    if (i >= 4) {
      const ma5 = result.slice(i - 4, i + 1).reduce((acc, curr) => acc + curr.close, 0) / 5;
      result[i].ma5 = Math.round(ma5 * 100) / 100;
    }
    if (i >= 19) {
      const ma20 = result.slice(i - 19, i + 1).reduce((acc, curr) => acc + curr.close, 0) / 20;
      result[i].ma20 = Math.round(ma20 * 100) / 100;
    }
    if (i >= 59) {
      const ma60 = result.slice(i - 59, i + 1).reduce((acc, curr) => acc + curr.close, 0) / 60;
      result[i].ma60 = Math.round(ma60 * 100) / 100;
    }
  }

  return result;
}
